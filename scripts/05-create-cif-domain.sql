CREATE SEQUENCE SHFQ_CIF.CITY_ID_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SHFQ_CIF.CUSTOMER_ID_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SHFQ_CIF.CUSTOMER_ADDRESS_ID_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SHFQ_CIF.CUSTOMER_CONTACT_ID_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SHFQ_CIF.SIGNATURE_ID_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SHFQ_CIF.CUSTOMER_INQUIRY_ID_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SHFQ_CIF.FUND_ID_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SHFQ_CIF.FUND_ADDRESS_ID_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SHFQ_CIF.FUND_CONTACT_ID_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SHFQ_CIF.BRANCH_ID_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SHFQ_CIF.BRANCH_ADDRESS_ID_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SHFQ_CIF.BRANCH_CONTACT_ID_SEQ START WITH 1 INCREMENT BY 1;

CREATE TABLE SHFQ_CIF.CITY (
  ID NUMBER(19,0) PRIMARY KEY, NAME VARCHAR2(255 CHAR),
  PHONE_CODE VARCHAR2(255 CHAR), CODE VARCHAR2(255 CHAR), PARENT_ID NUMBER(19,0)
);

CREATE TABLE SHFQ_CIF.CUSTOMER (
  ID NUMBER(19,0) PRIMARY KEY, FUND_ID NUMBER(19,0),
  IDENTIFIER VARCHAR2(255 CHAR) NOT NULL,
  CUSTOMER_TYPE NUMBER(3,0) NOT NULL,
  REGISTRATION_DATE TIMESTAMP(6) NOT NULL,
  CITY_ID NUMBER(19,0) NOT NULL,
  CUSTOMER_CODE VARCHAR2(255 CHAR), SHAHAB_CODE VARCHAR2(255 CHAR),
  FIRST_NAME VARCHAR2(255 CHAR), LAST_NAME VARCHAR2(255 CHAR),
  FATHER_NAME VARCHAR2(255 CHAR), DEATH_DATE TIMESTAMP(6),
  MARITAL_STATUS NUMBER(3,0), GENDER NUMBER(3,0),
  CUSTOMER_STATUS NUMBER(3,0) NOT NULL,
  CONSTRAINT CUSTOMER_FK_CITY FOREIGN KEY (CITY_ID) REFERENCES SHFQ_CIF.CITY(ID)
);

CREATE TABLE SHFQ_CIF.CUSTOMER_ADDRESS (
  ID NUMBER(19,0) PRIMARY KEY, FUND_ID NUMBER(19,0),
  ADDRESS_TYPE NUMBER(3,0), CITY_ID NUMBER(19,0) NOT NULL,
  ADDRESS VARCHAR2(255 CHAR), POSTAL_CODE VARCHAR2(255 CHAR),
  CUSTOMER_ID NUMBER(19,0) NOT NULL,
  CONSTRAINT CUSTOMER_ADDRESS_FK_CITY FOREIGN KEY (CITY_ID) REFERENCES SHFQ_CIF.CITY(ID),
  CONSTRAINT CUSTOMER_ADDRESS_FK_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES SHFQ_CIF.CUSTOMER(ID)
);

CREATE TABLE SHFQ_CIF.CUSTOMER_CONTACT (
  ID NUMBER(19,0) PRIMARY KEY, FUND_ID NUMBER(19,0),
  PHONE_NUMBER VARCHAR2(255 CHAR), MOBILE_NUMBER VARCHAR2(255 CHAR),
  CUSTOMER_ID NUMBER(19,0) NOT NULL,
  CONSTRAINT CUSTOMER_CONTACT_FK_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES SHFQ_CIF.CUSTOMER(ID)
);

CREATE TABLE SHFQ_CIF.SIGNATURE (
  ID NUMBER(19,0) PRIMARY KEY, FUND_ID NUMBER(19,0),
  FROM_DATE DATE, TO_DATE DATE,
  CUSTOMER_ID NUMBER(19,0), IMAGE RAW(1000), DESCRIPTION NVARCHAR2(300),
  CONSTRAINT FK_SIGNATURE_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES SHFQ_CIF.CUSTOMER(ID)
);

CREATE TABLE SHFQ_CIF.CUSTOMER_INQUIRY (
  ID NUMBER(19,0) PRIMARY KEY, FUND_ID NUMBER(19,0),
  CUSTOMER_TYPE NUMBER(3,0) NOT NULL, CUSTOMER_ID NUMBER(19,0) NOT NULL,
  RESPONSE VARCHAR2(255 CHAR), RESPONSE_VALUE NUMBER(10,0) NOT NULL,
  RESPONSE_HEADER VARCHAR2(255 CHAR), STATUS NUMBER(3,0),
  CUSTOMER_CONTACT_ID NUMBER(19,0),
  CONSTRAINT CUSTOMER_INQUIRY_FK_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES SHFQ_CIF.CUSTOMER(ID),
  CONSTRAINT CUSTOMER_INQUIRY_FK_CUSTOMER_CONTACT FOREIGN KEY (CUSTOMER_CONTACT_ID) REFERENCES SHFQ_CIF.CUSTOMER_CONTACT(ID)
);

CREATE TABLE SHFQ_CIF.FUND (
  ID NUMBER(19,0) PRIMARY KEY, CODE VARCHAR2(255 CHAR) NOT NULL,
  NAME VARCHAR2(255 CHAR) NOT NULL,
  OWNER_ID NUMBER(19,0) NOT NULL, TO_DATE TIMESTAMP(6),
  CONSTRAINT FUND_FK_OWNER FOREIGN KEY (OWNER_ID) REFERENCES SHFQ_CIF.CUSTOMER(ID),
  CONSTRAINT FUND_OWNER_UK UNIQUE (OWNER_ID)
);

CREATE TABLE SHFQ_CIF.BRANCH (
  ID NUMBER(19,0) PRIMARY KEY, CODE VARCHAR2(255 CHAR) NOT NULL,
  NAME VARCHAR2(255 CHAR) NOT NULL, FUND_ID NUMBER(19,0),
  TO_DATE TIMESTAMP(6),
  CONSTRAINT BRANCH_FK_FUND FOREIGN KEY (FUND_ID) REFERENCES SHFQ_CIF.FUND(ID),
  CONSTRAINT BRANCH_FUND_CODE_UK UNIQUE (FUND_ID, CODE)
);

CREATE TABLE SHFQ_CIF.BRANCH_ADDRESS (
  ID NUMBER(19,0) PRIMARY KEY, BRANCH_ID NUMBER(19,0) NOT NULL,
  CITY_ID NUMBER(19,0) NOT NULL, MAIN_STREET VARCHAR2(255 CHAR),
  STREET VARCHAR2(255 CHAR), ALLEY VARCHAR2(255 CHAR),
  TAG VARCHAR2(255 CHAR), POSTAL_CODE VARCHAR2(255 CHAR),
  UNIT VARCHAR2(255 CHAR),
  CONSTRAINT BRANCH_ADDRESS_BRANCH_UK UNIQUE (BRANCH_ID),
  CONSTRAINT BRANCH_ADDRESS_FK_BRANCH FOREIGN KEY (BRANCH_ID) REFERENCES SHFQ_CIF.BRANCH(ID),
  CONSTRAINT BRANCH_ADDRESS_FK_CITY FOREIGN KEY (CITY_ID) REFERENCES SHFQ_CIF.CITY(ID)
);

CREATE TABLE SHFQ_CIF.BRANCH_CONTACT (
  ID NUMBER(19,0) PRIMARY KEY, CONTACT_TYPE NUMBER(3,0),
  CONTACT_NUMBER VARCHAR2(255 CHAR), REGION_CODE NUMBER(10,0) NOT NULL,
  INTERNAL VARCHAR2(255 CHAR), BRANCH_ID NUMBER(19,0) NOT NULL,
  CONSTRAINT BRANCH_CONTACT_FK_BRANCH FOREIGN KEY (BRANCH_ID) REFERENCES SHFQ_CIF.BRANCH(ID)
);

CREATE TABLE SHFQ_CIF.FUND_ADDRESS (
  ID NUMBER(19,0) PRIMARY KEY, FUND_ID NUMBER(19,0) NOT NULL,
  CITY_ID NUMBER(19,0) NOT NULL, MAIN_STREET VARCHAR2(255 CHAR),
  STREET VARCHAR2(255 CHAR), ALLEY VARCHAR2(255 CHAR),
  TAG VARCHAR2(255 CHAR), POSTAL_CODE VARCHAR2(255 CHAR),
  UNIT VARCHAR2(255 CHAR),
  CONSTRAINT FUND_ADDRESS_FUND_UK UNIQUE (FUND_ID),
  CONSTRAINT FUND_ADDRESS_FK_FUND FOREIGN KEY (FUND_ID) REFERENCES SHFQ_CIF.FUND(ID),
  CONSTRAINT FUND_ADDRESS_FK_CITY FOREIGN KEY (CITY_ID) REFERENCES SHFQ_CIF.CITY(ID)
);

CREATE TABLE SHFQ_CIF.FUND_CONTACT (
  ID NUMBER(19,0) PRIMARY KEY, CONTACT_TYPE NUMBER(3,0),
  CONTACT_NUMBER VARCHAR2(255 CHAR), FUND_ID NUMBER(19,0) NOT NULL,
  REGION_CODE NUMBER(10,0) NOT NULL, INTERNAL VARCHAR2(255 CHAR),
  BRANCH_ID NUMBER(19,0) NOT NULL,
  CONSTRAINT FUND_CONTACT_FK_FUND FOREIGN KEY (FUND_ID) REFERENCES SHFQ_CIF.FUND(ID),
  CONSTRAINT FUND_CONTACT_FK_BRANCH FOREIGN KEY (BRANCH_ID) REFERENCES SHFQ_CIF.BRANCH(ID)
);
